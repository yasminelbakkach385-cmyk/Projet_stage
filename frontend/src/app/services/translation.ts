@Injectable({ providedIn: 'root' })
export class TranslationService {
  langueActuelle = signal<Langue>(this.recupererLangueSauvegardee());

  private recupererLangueSauvegardee(): Langue {
    return (localStorage.getItem('langue') as Langue) || 'fr';
  }

  changerLangue(langue: Langue): void {
    this.langueActuelle.set(langue);
    localStorage.setItem('langue', langue);
    document.documentElement.setAttribute('lang', langue);
    document.documentElement.setAttribute('dir', langue === 'ar' ? 'rtl' : 'ltr');
  }

  t(cle: string): string {
    return TRADUCTIONS[this.langueActuelle()][cle] || cle;
  }

  initialiser(): void {
    this.changerLangue(this.langueActuelle());
  }
}